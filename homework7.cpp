//

#include <iostream>                 // Подключает библиотеку для ввода и вывода (cin, cout)
#include <cmath>                   // Подключает математические функции (например, sqrt для квадратного корня)
#include <iomanip>                  // Подключает манипуляторы для форматирования вывода (setprecision, fixed)
#include <windows.h>   // нужно для SetConsoleOutputCP

int main() { // Начало функции main — точка входа в программу
    setlocale(LC_ALL, "RUS");
    
        double a, b, c;                 // Объявляем три переменные типа double для коэффициентов a, b, c

        std::cout << "Введите коэффициенты a, b и c (ax^2 + bx + c = 0): ";  // Выводим приглашение для пользователя
        if (!(std::cin >> a >> b >> c)) {  // Пытаемся считать три числа; если ввод некорректен, условие станет true
            std::cerr << "Ошибка ввода.\n";  // Выводим сообщение об ошибке в поток ошибок
            return 1;                    // Завершаем программу с кодом ошибки (1 означает «неуспешное завершение»)
        }

        // Случай линейного уравнения (a == 0)
        if (a == 0.0) {                  // Проверяем, равен ли коэффициент при x^2 нулю — тогда уравнение не квадратное
            if (b == 0.0) {              // Если и b тоже ноль, уравнение вырождается дальше
                if (c == 0.0) {          // Если c тоже ноль: 0 = 0 — верно при любом x
                    std::cout << "Уравнение имеет бесконечно много решений (0 = 0).\n";
                }
                else {                 // Если c ≠ 0: например, 5 = 0 — противоречие, решений нет
                    std::cout << "Нет решений (противоречие: " << c << " = 0).\n";
                }
            }
            else {                     // Если b ≠ 0, уравнение линейное: bx + c = 0
                double x = -c / b;       // Находим единственный корень по формуле x = -c/b
                std::cout << "Линейное уравнение. Один корень: x = " << x << "\n";
            }
            return 0;                    // Завершаем программу успешно (0 — стандартный код успеха)
        }

        double discriminant = b * b - 4 * a * c;  // Вычисляем дискриминант D = b^2 - 4ac
        const double eps = 1e-9;         // Объявляем маленькое число (порог погрешности) для безопасного сравнения с нулём

        if (std::abs(discriminant) < eps) {  // Если модуль дискриминанта меньше порога — считаем его нулём (с учётом погрешностей вычислений)
            // Один корень (дискриминант ≈ 0)
            double x = -b / (2 * a);     // Формула для единственного корня: x = -b/(2a)
            std::cout << "Один корень: x = "
                << std::fixed << std::setprecision(6) << x << "\n";  // fixed+setprecision задают 6 знаков после запятой
        }
        else if (discriminant > 0) {   // Если дискриминант строго больше нуля — два различных действительных корня
            double sqrt_d = std::sqrt(discriminant);  // Вычисляем квадратный корень из дискриминанта
            double x1 = (-b + sqrt_d) / (2 * a);       // Первый корень по формуле (-b + √D)/(2a)
            double x2 = (-b - sqrt_d) / (2 * a);       // Второй корень по формуле (-b - √D)/(2a)
            std::cout << "Два корня:\n";               // Печатаем заголовок
            std::cout << "x1 = " << std::fixed << std::setprecision(6) << x1 << "\n";  // Вывод первого корня
            std::cout << "x2 = " << std::fixed << std::setprecision(6) << x2 << "\n";  // Вывод второго корня
        }
        else {
            std::cout << "Нет решений\n";  // Сообщаем, что при d<0 нет решений
        }

        return 0;                        // Успешное завершение программы
 
}