// homework7.cpp : Этот файл содержит функцию "main". Здесь начинается и заканчивается выполнение программы.
//

#include <iostream>      // Подключаем библиотеку для ввода/вывода (std::cin, std::cout)
#include <algorithm>     // Подключаем алгоритмы STL, в том числе std::sort (быстрая сортировка)

int main() {             // Точка входа в программу: с этой строки начинается выполнение
    const int n = 5;      // Объявляем константу n = 5 — размер нашего статического массива
    int arr[n] = { 34, 7, 23, 32, 5 };  // Объявляем массив из 5 целых чисел и сразу инициализируем значениями

    // --- Пузырьковая сортировка (учебный пример, чтобы показать работу с индексами) ---
    for (int i = 0; i < n - 1; ++i) {          // Внешний цикл: i — номер прохода по массиву (от 0 до n-2)
        for (int j = 0; j < n - i - 1; ++j) {  // Внутренний цикл: сравниваем соседние элементы, «толкаем» максимум в конец
            if (arr[j] > arr[j + 1]) {        // Если текущий элемент больше следующего — нужно поменять местами
                int tmp = arr[j];              // Сохраняем значение arr[j] во временную переменную tmp
                arr[j] = arr[j + 1];          // Записываем в arr[j] значение следующего элемента
                arr[j + 1] = tmp;              // В arr[j+1] записываем сохранённое значение (меняем местами)
            }
        }
    }

    std::cout << "Отсортированный массив (пузырьком): ";  // Выводим текст-подсказку в консоль
    for (int x : arr) {                 // Range-based for: перебираем все элементы массива без явных индексов
        std::cout << x << " ";          // Выводим каждый элемент и пробел после него
    }
    std::cout << "\n";                  // Переводим строку после вывода всех элементов

    // --- Сортировка через стандартную библиотеку (реальный способ) ---
    std::sort(arr, arr + n);            // Сортирует диапазон [arr, arr+n): от начала массива до конца

    std::cout << "Через std::sort: ";   // Текст-подсказка
    for (int x : arr) {                 // Снова перебираем элементы
        std::cout << x << " ";           // Выводим их
    }
    std::cout << "\n";                   // Перевод строки

    return 0;                            // Завершаем программу с кодом успеха (0)
}
